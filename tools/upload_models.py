"""Upload Blender models (art/out/<Name>.glb) to Roblox as Models, grant Use to Dev's alt
(User 347852675; the API only allows dependency grants for universes) and write
src/shared/Config/Models.luau (name -> asset id).

  python3 tools/upload_models.py Base Roller_1 ...   # these names
  python3 tools/upload_models.py                     # every new or changed GLB in art/out

Build the GLBs first: cd art/blender && python base.py (see art/blender/kit.py).
Needs env ROBLOXAPIKEY (never printed). Cached by file hash in art/models.lock.json.
"""
import hashlib, json, os, sys, time, uuid

sys.path.insert(0, os.path.dirname(__file__))
from upload_images import ROOT, CREATOR, request  # noqa: E402

OUT = os.path.join(ROOT, "art", "out")
LOCK = os.path.join(ROOT, "art", "models.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "Config", "Models.luau")
ALT = "347852675"


def upload(path, name):
    meta = {"assetType": "Model", "displayName": ("Snowball_" + name)[:50], "description": f"Roll the Snowball model: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{name}.glb\"\r\nContent-Type: model/gltf-binary\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    for attempt in range(5):
        code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
        if code == 429 or code >= 500:
            time.sleep(2 ** attempt * 2)
            continue
        break
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    p = op.get("path")
    for _ in range(150):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{p}")
    asset = (op.get("response") or {}).get("assetId")
    if not asset:
        raise RuntimeError(f"upload {name}: no asset id ({op})")
    return int(asset)


def grant(asset):
    body = {"subjectType": "User", "subjectId": ALT, "action": "Use",
            "requests": [{"assetId": asset, "grantToDependencies": False}]}
    code, res = request("PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                        json.dumps(body).encode(), {"Content-Type": "application/json-patch+json"})
    # 200 can still carry a refusal in the body (asset still processing): check it.
    if code < 300 and int(asset) not in [int(a) for a in (res or {}).get("successAssetIds", [])]:
        return 409
    return code


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    names = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not names:
        names = [os.path.splitext(f)[0] for f in sorted(os.listdir(OUT)) if f.endswith(".glb")]
    for name in names:
        path = os.path.join(OUT, f"{name}.glb")
        digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if "--force" not in sys.argv and lock.get(name, {}).get("sha") == digest:
            continue
        asset = upload(path, name)
        lock[name] = {"id": asset, "sha": digest, "granted": False}
        json.dump(lock, open(LOCK, "w"), indent=1, sort_keys=True)
        print(f"{name}: {asset}", flush=True)
    for name, e in lock.items():
        if not e.get("granted"):
            code = grant(e["id"])
            e["granted"] = code < 300
            print(f"grant {name} -> {ALT}: {code}", flush=True)
    json.dump(lock, open(LOCK, "w"), indent=1, sort_keys=True)
    meta_path = os.path.join(OUT, "meta.json")
    meta = json.load(open(meta_path)) if os.path.exists(meta_path) else {}
    lines = ["--!strict", "-- Generated by tools/upload_models.py. Do not edit by hand.",
             "-- Center = the model's bounding-box centre in model-local studs (floor at y = 0);",
             "-- pivot the loaded model on its bounding box and place it at origin * Center.",
             "return {"]
    for name in sorted(lock):
        c = meta.get(name, {}).get("center", [0, 0, 0])
        lines.append(f"\t{name} = {{ Id = {lock[name]['id']}, Center = Vector3.new({c[0]}, {c[1]}, {c[2]}) }},")
    lines.append("} :: { [string]: { Id: number, Center: Vector3 } }")
    open(LUA, "w").write("\n".join(lines) + "\n")
    print(f"{len(lock)} models in Config/Models.luau")


if __name__ == "__main__":
    main()

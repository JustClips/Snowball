"""Upload UI images (art/icons/*.png, art/ui/*.png) to Roblox and write
src/shared/Config/Images.luau (name -> rbxassetid).

  python3 tools/upload_images.py          # new or changed files only
  python3 tools/upload_images.py --force  # re-upload everything

Needs env ROBLOXAPIKEY (Open Cloud key with asset write for user 822623546). The key is
never printed. Results are cached by file hash in art/images.lock.json.
Every image must be checked first: no text, URLs, watermarks or credit lines (project rule).
"""
import hashlib, json, os, ssl, sys, time, urllib.error, urllib.request, uuid

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DIRS = [os.path.join(ROOT, "art", "icons"), os.path.join(ROOT, "art", "ui")]
LOCK = os.path.join(ROOT, "art", "images.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "Config", "Images.luau")
CREATOR = "822623546"


def ctx():
    for p in (os.environ.get("SSL_CERT_FILE"), "/root/.ccr/ca-bundle.crt"):
        if p and os.path.exists(p):
            return ssl.create_default_context(cafile=p)
    return ssl.create_default_context()


CTX = ctx()


def request(method, url, body=None, headers=None):
    h = {"x-api-key": os.environ["ROBLOXAPIKEY"]}
    h.update(headers or {})
    r = urllib.request.Request(url, data=body, method=method, headers=h)
    try:
        with urllib.request.urlopen(r, context=CTX, timeout=120) as resp:
            data = resp.read()
            return resp.status, json.loads(data) if data else {}
    except urllib.error.HTTPError as e:
        data = e.read().decode(errors="replace")
        try:
            return e.code, json.loads(data)
        except Exception:
            return e.code, {"raw": data[:300]}


def upload(path, name):
    meta = {"assetType": "Image", "displayName": ("Snowball_" + name)[:50], "description": f"Roll the Snowball UI: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{name}.png\"\r\nContent-Type: image/png\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    for attempt in range(5):
        code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
        if code == 429 or code >= 500:
            time.sleep(2 ** attempt * 2)
            continue
        break
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    path_ = op.get("path")
    for _ in range(60):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{path_}")
    asset = (op.get("response") or {}).get("assetId")
    if not asset:
        raise RuntimeError(f"upload {name}: no asset id ({op})")
    return int(asset)


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    force = "--force" in sys.argv
    for d in DIRS:
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".png"):
                continue
            name = os.path.splitext(f)[0]
            path = os.path.join(d, f)
            digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
            if not force and lock.get(name, {}).get("sha") == digest:
                continue
            asset = upload(path, name)
            lock[name] = {"id": asset, "sha": digest}
            print(f"{name}: {asset}", flush=True)
            json.dump(lock, open(LOCK, "w"), indent=1, sort_keys=True)
    lines = ["--!strict", "-- Generated by tools/upload_images.py. Do not edit by hand.", "return {"]
    for name in sorted(lock):
        lines.append(f'\t{name} = "rbxassetid://{lock[name]["id"]}",')
    lines.append("} :: { [string]: string }")
    open(LUA, "w").write("\n".join(lines) + "\n")
    print(f"{len(lock)} images in Config/Images.luau")


if __name__ == "__main__":
    main()

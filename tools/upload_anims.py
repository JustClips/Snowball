"""Upload KeyframeSequence animations (art/out/anims/*.rbxmx, made by art/anim/*.py) as
Animation assets, grant Use to Dev's alt (347852675) and write src/shared/Config/Anims.luau.

  python3 tools/upload_anims.py            # new or changed clips
Needs env ROBLOXAPIKEY (never printed). Cached by hash in art/anims.lock.json.
"""
import hashlib, json, os, sys, time, uuid

sys.path.insert(0, os.path.dirname(__file__))
from upload_images import ROOT, CREATOR, request  # noqa: E402
from upload_models import grant  # noqa: E402

DIR = os.path.join(ROOT, "art", "out", "anims")
LOCK = os.path.join(ROOT, "art", "anims.lock.json")
LUA = os.path.join(ROOT, "src", "shared", "Config", "Anims.luau")


def upload(path, name):
    meta = {"assetType": "Animation", "displayName": ("Snowball_" + name)[:50], "description": f"Roll the Snowball animation: {name}",
            "creationContext": {"creator": {"userId": CREATOR}}}
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n"
            f"{json.dumps(meta)}\r\n--{b}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{name}.rbxm\"\r\nContent-Type: model/x-rbxm\r\n\r\n").encode() + open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    code, op = request("POST", "https://apis.roblox.com/assets/v1/assets", body, {"Content-Type": f"multipart/form-data; boundary={b}"})
    if code >= 300:
        raise RuntimeError(f"upload {name} failed: {code} {op}")
    p = op.get("path")
    for _ in range(90):
        if op.get("done"):
            break
        time.sleep(2)
        code, op = request("GET", f"https://apis.roblox.com/assets/v1/{p}")
    asset = (op.get("response") or {}).get("assetId")
    if not asset:
        raise RuntimeError(f"upload {name}: no asset id ({op})")
    return int(asset)


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    for f in sorted(os.listdir(DIR)):
        if not f.endswith(".rbxmx"):
            continue
        name = f[:-6]
        path = os.path.join(DIR, f)
        digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if lock.get(name, {}).get("sha") == digest:
            continue
        asset = upload(path, name)
        lock[name] = {"id": asset, "sha": digest, "granted": grant(asset) < 300}
        print(f"{name}: {asset} granted={lock[name]['granted']}", flush=True)
        json.dump(lock, open(LOCK, "w"), indent=1, sort_keys=True)
    lines = ["--!strict", "-- Generated by tools/upload_anims.py. Do not edit by hand.", "return {"]
    for name in sorted(lock):
        lines.append(f'\t{name} = "rbxassetid://{lock[name]["id"]}",')
    lines.append("} :: { [string]: string }")
    open(LUA, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes src/shared/Config/Track.luau: the graybox mountain run (GAME_PLAN §5.4).

A control point every STEP studs: { Pos, Width, Slope, Surface }. Gentle S-curves, the
slope and surface follow the zones. The Blender export (art thread) will write the same
format, so the game code never changes when the real mountain arrives.
"""
import math, pathlib

STEP = 100
LENGTH = 6100
START = (0.0, 1000.0, 24.0)  # first point: the edge of the launch deck, heading +Z

# (from s, slope (drop per stud), surface, width)
SECTIONS = [
    (0, 0.20, "Snow", 120),      # Summit Meadow
    (400, 0.22, "Snow", 120),    # Pine Forest
    (1000, 0.07, "Ice", 120),    # Frozen Lake: flat and slidey
    (2000, 0.16, "Snow", 90),    # Ice Cave: narrower
    (3500, 0.21, "Powder", 120), # Aurora Valley
    (5500, 0.05, "Snow", 120),   # The Village
]

def section(s):
    cur = SECTIONS[0]
    for sec in SECTIONS:
        if s >= sec[0]:
            cur = sec
    return cur

def heading(s):
    # radians from +Z; gentle S-curves that grow a little down the mountain
    if s < 150:
        return 0.0
    amp = 0.28 + 0.10 * min(1.0, s / 4000)
    return amp * math.sin((s - 150) / 520.0) + 0.12 * math.sin((s - 150) / 205.0)

pts = []
x, y, z = START
s = 0.0
while s <= LENGTH:
    _, slope, surface, width = section(s)
    pts.append((x, y, z, width, slope, surface))
    # integrate the next STEP studs of horizontal travel in small pieces
    for _ in range(10):
        h = heading(s)
        slope_here = section(s)[1]
        d = STEP / 10
        horiz = d / math.sqrt(1 + slope_here ** 2)
        x += math.sin(h) * horiz
        z += math.cos(h) * horiz
        y -= slope_here * horiz
        s += d

out = ["--!strict",
       "-- GENERATED by tools/gen_track.py (graybox). The Blender export replaces this file in the",
       "-- same format: one point every ~100 studs along the run, top to bottom.",
       "local Types = require(script.Parent.Parent.Types)", "",
       "local Points: { Types.TrackPoint } = {"]
for (x, y, z, w, sl, sf) in pts:
    out.append(f'\t{{ Pos = Vector3.new({x:.1f}, {y:.1f}, {z:.1f}), Width = {w}, Slope = {sl}, Surface = "{sf}" }},')
out += ["}", "", "return {", "\tId = \"Mountain1\",", "\tPoints = Points,", "}", ""]
p = pathlib.Path(__file__).resolve().parent.parent / "src/shared/Config/Track.luau"
p.write_text("\n".join(out))
print(f"{len(pts)} points, end at y={pts[-1][1]:.0f}, x={pts[-1][0]:.0f}, z={pts[-1][2]:.0f}")
